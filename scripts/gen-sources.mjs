// Writes src/api/sources.ts from the `source` enum in openapi.json, so the platform
// lists in the UI follow the contract and never need a hand edit.
import { readFileSync, writeFileSync } from 'node:fs';

const spec = JSON.parse(readFileSync(new URL('../openapi.json', import.meta.url), 'utf8'));
const values = spec.components.schemas.SourceHealth?.properties?.source?.enum;

if (!Array.isArray(values) || values.length === 0) {
  throw new Error('openapi.json: components.schemas.SourceHealth.properties.source has no enum');
}

const items = values.map((v) => `'${v}'`);
const oneLine = `export const PLATFORMS = [${items.join(', ')}] as const;`;
const list =
  oneLine.length <= 100
    ? oneLine
    : `export const PLATFORMS = [\n${items.map((i) => `  ${i},`).join('\n')}\n] as const;`;
const out = `// Generated by scripts/gen-sources.mjs from openapi.json. Do not edit.\n${list}\n`;

writeFileSync(new URL('../src/api/sources.ts', import.meta.url), out);
