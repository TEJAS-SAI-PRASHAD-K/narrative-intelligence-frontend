import { PencilLine, Sparkles } from 'lucide-react';
import type { AiProvenance } from '@/api/types';
import { Badge } from '@/components/ui/badge';
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip';
import { formatDateTime, formatRelative } from '@/lib/format';

/**
 * Provenance is read from the data, never assumed.
 *
 * The pill is driven entirely by `GeneratedText.provenance`. There is no list in the
 * frontend of "which fields are AI-written" -- the day the backend starts generating
 * a field that used to be human, or stops, the UI follows without a change here.
 */
export function AiPill({ provenance }: { provenance: AiProvenance }) {
  const edited = provenance.edited_by_user === true;
  const generatedAt = provenance.generated_at ?? null;

  if (provenance.generated_by === 'human' && !edited) {
    return null;
  }

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <Badge variant={edited ? 'muted' : 'ai'} className="cursor-help">
          {edited ? (
            <>
              <PencilLine className="h-2.5 w-2.5" aria-hidden="true" />
              Edited by analyst
            </>
          ) : (
            <>
              <Sparkles className="h-2.5 w-2.5" aria-hidden="true" />
              Generated by AI
            </>
          )}
        </Badge>
      </TooltipTrigger>
      <TooltipContent>
        <dl className="space-y-1">
          <Row label="Source" value={sourceLabel(provenance)} />
          {provenance.model && <Row label="Model" value={provenance.model} mono />}
          {provenance.prompt_version && (
            <Row label="Prompt" value={provenance.prompt_version} mono />
          )}
          {generatedAt && (
            <Row
              label="Generated"
              value={`${formatRelative(generatedAt)} (${formatDateTime(generatedAt, 'UTC')} UTC)`}
            />
          )}
          {edited && (
            <p className="pt-1 text-muted-foreground">
              An analyst has edited this text since it was generated.
            </p>
          )}
        </dl>
      </TooltipContent>
    </Tooltip>
  );
}

function sourceLabel(p: AiProvenance): string {
  if (p.edited_by_user) return 'AI draft, analyst-edited';
  if (p.generated_by === 'ai') return 'Generated by a language model';
  if (p.generated_by === 'heuristic') return 'Derived by a rule, not a model';
  return 'Written by a person';
}

function Row({ label, value, mono }: { label: string; value: string; mono?: boolean }) {
  return (
    <div className="flex gap-2">
      <dt className="shrink-0 text-muted-foreground">{label}</dt>
      <dd className={mono ? 'font-mono' : undefined}>{value}</dd>
    </div>
  );
}
