import { ExternalLink, FileSearch, RefreshCw, ShieldAlert, ThumbsDown, ThumbsUp } from 'lucide-react';
import { useMemo, useState } from 'react';
import type { Citation, CompassContext } from '@/api/types';
import { RiskDot } from '@/components/risk/RiskDot';
import { riskLevelFromBand } from '@/components/risk/riskLevel';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import {
  Accordion,
  AccordionContent,
  AccordionItem,
  AccordionTrigger,
} from '@/components/ui/accordion';
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip';
import { formatDateTime, formatRelative, humanizeEnum } from '@/lib/format';
import { cn } from '@/lib/utils';
import { citationNumbers, segmentContext } from './citations';

/**
 * Compass Context — the differentiator.
 *
 * Two things here are non-negotiable:
 *
 *  1. Citations render *inline, at their character spans*. The backend returns
 *     `char_start`/`char_end` so a reader can see which sentence each source
 *     supports. A flat bibliography under the paragraph would technically list the
 *     same URLs while telling the analyst nothing about what is sourced and what is
 *     the model talking.
 *
 *  2. `verification_status: "insufficient_evidence"` with an empty context renders an
 *     explicit "the system could not source this claim" state. Not an empty box, not
 *     a spinner that never resolves. A blank panel reads as "still loading" and an
 *     analyst will wait for something that is never coming.
 */

const STATUS_VARIANT: Record<
  CompassContext['verification_status'],
  'risk-high' | 'risk-med' | 'risk-low' | 'risk-none'
> = {
  substantiated: 'risk-low',
  partially_substantiated: 'risk-med',
  unverified: 'risk-none',
  insufficient_evidence: 'risk-none',
  debunked: 'risk-high',
};

const STATUS_EXPLAIN: Record<CompassContext['verification_status'], string> = {
  substantiated: 'Retrieved sources support the claim as stated.',
  partially_substantiated:
    'Some elements are supported by retrieved sources and others are not. Read the context for which is which.',
  unverified: 'No retrieved source contradicts or confirms the claim.',
  insufficient_evidence:
    'Retrieval did not return enough material to say anything about this claim.',
  debunked: 'Retrieved sources contradict the claim as stated.',
};

export function CompassModule({
  context,
  onRegenerate,
  onFeedback,
  regenerating,
  className,
}: {
  context: CompassContext;
  onRegenerate: () => void;
  onFeedback: (helpful: boolean) => void;
  regenerating?: boolean;
  className?: string;
}) {
  const [vote, setVote] = useState<boolean | null>(null);

  const numbers = useMemo(() => citationNumbers(context.citations ?? []), [context.citations]);
  const { segments, unanchored } = useMemo(
    () => segmentContext(context.context ?? '', context.citations ?? []),
    [context.context, context.citations],
  );

  const couldNotSource =
    context.verification_status === 'insufficient_evidence' ||
    (context.context ?? '').trim().length === 0;

  return (
    <section className={cn('rounded-lg border border-border bg-card', className)}>
      <header className="flex flex-wrap items-center gap-2 border-b border-border px-3 py-2">
        <h3 className="text-xs font-semibold">Compass Context</h3>

        <Tooltip>
          <TooltipTrigger asChild>
            <Badge variant={STATUS_VARIANT[context.verification_status]} className="cursor-help">
              {humanizeEnum(context.verification_status)}
            </Badge>
          </TooltipTrigger>
          <TooltipContent>{STATUS_EXPLAIN[context.verification_status]}</TooltipContent>
        </Tooltip>

        <span className="flex items-center gap-1 text-2xs text-muted-foreground">
          Risk
          <RiskDot level={riskLevelFromBand(context.risk)} label={humanizeEnum(context.risk)} />
        </span>

        <Badge variant="ai">
          {context.generated_by === 'ai' ? 'Generated by AI' : humanizeEnum(context.generated_by)}
        </Badge>

        <div className="flex-1" />

        <div className="flex items-center gap-0.5" role="group" aria-label="Rate this Compass context">
          <Button
            variant="ghost"
            size="icon-sm"
            aria-label="Mark this context helpful"
            aria-pressed={vote === true}
            className={cn(vote === true && 'text-risk-low')}
            onClick={() => {
              setVote(true);
              onFeedback(true);
            }}
          >
            <ThumbsUp className="h-3 w-3" aria-hidden="true" />
          </Button>
          <Button
            variant="ghost"
            size="icon-sm"
            aria-label="Mark this context unhelpful"
            aria-pressed={vote === false}
            className={cn(vote === false && 'text-risk-high')}
            onClick={() => {
              setVote(false);
              onFeedback(false);
            }}
          >
            <ThumbsDown className="h-3 w-3" aria-hidden="true" />
          </Button>
        </div>

        <Button variant="outline" size="sm" onClick={onRegenerate} disabled={regenerating}>
          <RefreshCw className={cn('h-3 w-3', regenerating && 'animate-spin')} aria-hidden="true" />
          {regenerating ? 'Queued' : 'Regenerate'}
        </Button>
      </header>

      <div className="space-y-3 px-3 py-3">
        <Field label="Claim">
          <p className="text-sm leading-relaxed">{context.claim}</p>
        </Field>

        <Field label="Context">
          {couldNotSource ? (
            <CouldNotSource context={context} />
          ) : (
            <p className="text-sm leading-loose">
              {segments.map((segment, i) => (
                <span
                  key={i}
                  className={cn(
                    segment.citations.length > 0 &&
                      'border-b border-dotted border-primary/50 bg-primary/[0.04]',
                  )}
                >
                  {segment.text}
                  {segment.citations.map((c) => (
                    <CitationMark key={c.id} citation={c} number={numbers.get(c.id) ?? 0} />
                  ))}
                </span>
              ))}
            </p>
          )}
        </Field>

        {context.caution_note && (
          <div className="flex gap-2 rounded-md border border-risk-med/40 bg-risk-med-bg p-2.5">
            <ShieldAlert className="mt-0.5 h-3.5 w-3.5 shrink-0 text-risk-med" aria-hidden="true" />
            <div>
              <p className="text-2xs font-medium uppercase tracking-wide text-risk-med">Caution</p>
              <p className="mt-0.5 text-xs leading-relaxed">{context.caution_note}</p>
            </div>
          </div>
        )}

        {unanchored.length > 0 && (
          <Field label="Additional sources (no span returned)">
            <ul className="space-y-1">
              {unanchored.map((c) => (
                <li key={c.id}>
                  <CitationLink citation={c} number={numbers.get(c.id) ?? 0} />
                </li>
              ))}
            </ul>
          </Field>
        )}

        {(context.citations?.length ?? 0) > 0 && (
          <Field label={`Sources (${context.citations?.length})`}>
            <ol className="space-y-1.5">
              {(context.citations ?? []).map((c) => (
                <li key={c.id} className="text-xs">
                  <CitationLink citation={c} number={numbers.get(c.id) ?? 0} />
                  {c.snippet && (
                    <p className="ml-5 mt-0.5 text-2xs italic text-muted-foreground">
                      “{c.snippet}”
                    </p>
                  )}
                </li>
              ))}
            </ol>
          </Field>
        )}

        <Accordion type="single" collapsible>
          <AccordionItem value="provenance" className="border-b-0">
            <AccordionTrigger className="text-2xs uppercase tracking-wide text-muted-foreground">
              Generation details
            </AccordionTrigger>
            <AccordionContent>
              <dl className="grid grid-cols-2 gap-x-4 gap-y-1 text-2xs">
                <Row label="Model" value={context.model} mono />
                <Row label="Prompt version" value={context.prompt_version} mono />
                <Row
                  label="Generated"
                  value={`${formatRelative(context.generated_at)} (${formatDateTime(context.generated_at, 'UTC')} UTC)`}
                />
                <Row label="Attempts" value={String(context.attempts ?? 1)} />
                <Row
                  label="Documents retrieved"
                  value={String(context.retrieved_document_count ?? 0)}
                />
                <Row label="Context id" value={context.id} mono />
                {context.superseded_by && (
                  <Row label="Superseded by" value={context.superseded_by} mono />
                )}
              </dl>
            </AccordionContent>
          </AccordionItem>
        </Accordion>
      </div>
    </section>
  );
}

/**
 * The explicit failure state. It names what was tried (attempts, documents retrieved)
 * so an analyst can tell "retrieval found nothing" from "retrieval never ran".
 */
function CouldNotSource({ context }: { context: CompassContext }) {
  return (
    <div className="flex gap-2.5 rounded-md border border-dashed border-border bg-surface-sunken p-3">
      <FileSearch className="mt-0.5 h-4 w-4 shrink-0 text-muted-foreground" aria-hidden="true" />
      <div className="space-y-1.5">
        <p className="text-xs font-medium">The system could not source this claim.</p>
        <p className="text-2xs leading-relaxed text-muted-foreground">
          Retrieval ran {context.attempts ?? 1} time{(context.attempts ?? 1) === 1 ? '' : 's'} and
          returned {context.retrieved_document_count ?? 0} usable document
          {(context.retrieved_document_count ?? 0) === 1 ? '' : 's'}. No context is shown because
          there is nothing to show — this is not a rendering failure and not a claim that the
          narrative is false.
        </p>
        <p className="text-2xs leading-relaxed text-muted-foreground">
          Regenerating may help if the corpus or the retrieval index has changed since{' '}
          {formatDateTime(context.generated_at, 'UTC')} UTC.
        </p>
      </div>
    </div>
  );
}

/** Superscript link, inline at the span it supports. */
function CitationMark({ citation, number }: { citation: Citation; number: number }) {
  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <a
          href={citation.url}
          target="_blank"
          rel="noreferrer noopener"
          aria-label={`Source ${number}: ${citation.title ?? citation.url}`}
          className="ml-0.5 rounded-sm align-super text-[9px] font-semibold text-primary hover:underline focus-visible:ring-2 focus-visible:ring-ring"
        >
          [{number}]
        </a>
      </TooltipTrigger>
      <TooltipContent>
        <p className="font-medium">{citation.title ?? citation.url}</p>
        {citation.publisher && <p className="text-muted-foreground">{citation.publisher}</p>}
        {citation.snippet && <p className="mt-1 italic">“{citation.snippet}”</p>}
        {citation.retrieved_at && (
          <p className="mt-1 text-muted-foreground">
            Retrieved {formatDateTime(citation.retrieved_at, 'UTC')} UTC
          </p>
        )}
      </TooltipContent>
    </Tooltip>
  );
}

function CitationLink({ citation, number }: { citation: Citation; number: number }) {
  return (
    <a
      href={citation.url}
      target="_blank"
      rel="noreferrer noopener"
      className="inline-flex items-start gap-1.5 rounded-sm text-primary hover:underline focus-visible:ring-2 focus-visible:ring-ring"
    >
      <span className="shrink-0 font-mono text-2xs text-muted-foreground">[{number}]</span>
      <span className="min-w-0">
        <span className="break-words">{citation.title ?? citation.url}</span>
        {citation.publisher && (
          <span className="ml-1 text-2xs text-muted-foreground">— {citation.publisher}</span>
        )}
      </span>
      <ExternalLink className="mt-0.5 h-2.5 w-2.5 shrink-0 opacity-60" aria-hidden="true" />
    </a>
  );
}

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="space-y-1">
      <span className="block text-2xs font-semibold uppercase tracking-wide text-muted-foreground">
        {label}
      </span>
      {children}
    </div>
  );
}

function Row({ label, value, mono }: { label: string; value: string | null; mono?: boolean }) {
  if (!value) return null;
  return (
    <>
      <dt className="text-muted-foreground">{label}</dt>
      <dd className={cn('truncate', mono && 'font-mono')} title={value}>
        {value}
      </dd>
    </>
  );
}
